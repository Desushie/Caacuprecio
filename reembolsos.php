<h2>1. Caacuprecio no vende ni cobra</h2>
<p>Caacuprecio es un comparador gratuito. No vendemos productos, no procesamos pagos y no cobramos nada a los usuarios. Por eso <strong>no hay compras que reembolsar en Caacuprecio</strong>: crear una cuenta, guardar favoritos y comparar precios es gratis.</p>

<h2>2. Compras hechas en una tienda</h2>
<p>Cuando compras un producto que viste en Caacuprecio, el contrato es entre tú y la tienda. La tienda es la responsable de:</p>
<ul>
  <li>Confirmar el precio final, el stock y las condiciones de venta.</li>
  <li>La entrega, la garantía, los cambios, las devoluciones y los reembolsos.</li>
</ul>
<p>Antes de comprar, revisa la política de cambios y devoluciones de la tienda. Encontrarás su sitio web y sus datos de contacto en la página de cada tienda dentro de Caacuprecio.</p>

<h2>3. Tus derechos como consumidor</h2>
<p>La Ley N° 1334/1998 de Defensa del Consumidor y del Usuario protege tus compras en las tiendas. Entre otros derechos:</p>
<ul>
  <li>Si compras fuera del local comercial (por ejemplo, por internet o por teléfono), la ley te permite, en general, arrepentirte de la compra dentro de los 7 días desde que la hiciste o recibiste el producto. Consulta con la tienda las condiciones para ejercerlo.</li>
  <li>Tienes derecho a recibir información veraz sobre el precio y las características del producto, y a la garantía que corresponda.</li>
</ul>
<p>Si tienes un problema con una tienda y no lo resuelven, puedes acudir a la Secretaría de Defensa del Consumidor y el Usuario (SEDECO).</p>

<h2>4. Si el precio en Caacuprecio no coincide</h2>
<p>Los precios del sitio se toman de las tiendas y pueden estar desactualizados. Si la tienda te cobra un precio distinto al que viste aquí, vale el precio que informe la tienda; Caacuprecio no puede obligarla a respetar el precio mostrado ni reembolsar la diferencia. Ayúdanos a corregirlo con el botón "Reportar" del producto.</p>
